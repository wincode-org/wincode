// Generates lib/src/workflow_template.g.dart from templates/wincode-ios.yml, so that a compiled wincode can write the
// reference workflow without the source tree. templates/wincode-ios.yml stays the readable source.
//
// Run it from packages/wincode_cli after changing the template:
//
//   dart run tool/embed_template.dart
//
// test/workflow_template_test.dart fails when the constant and the file differ.
import 'dart:io';

/// The source of `workflow_template.g.dart` for the template text [template].
///
/// The text goes into a raw multi-line string, which holds it byte for byte as long as it has no `'''` and no carriage
/// return, and is valid text. Anything else is refused, so that a change to the template cannot silently change.
String embeddedTemplateSource(String template) {
  if (template.contains("'''")) {
    throw const FormatException(
      "the template contains ''', which a raw string cannot hold",
    );
  }
  if (template.contains('\r')) {
    throw const FormatException(
      'the template contains a carriage return: save it with LF line ends',
    );
  }
  return '''
// GENERATED by tool/embed_template.dart from templates/wincode-ios.yml. Do not edit: run
//   dart run tool/embed_template.dart
// test/workflow_template_test.dart checks that this constant and the file are the same bytes.

/// The reference workflow that `wincode init --workflow` writes (ADR-0013, section 3).
const workflowTemplate = r\'\'\'
$template\'\'\';
''';
}

void main() {
  final file = File('templates/wincode-ios.yml');
  if (!file.existsSync()) {
    stderr.writeln(
      'Run this from packages/wincode_cli: templates/wincode-ios.yml is not here.',
    );
    exit(64);
  }
  File('lib/src/workflow_template.g.dart')
      .writeAsStringSync(embeddedTemplateSource(file.readAsStringSync()));
  final result = Process.runSync(Platform.resolvedExecutable, [
    'format',
    'lib/src/workflow_template.g.dart',
  ]);
  stdout.write(result.stdout);
}
